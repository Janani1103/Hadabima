export function translate(text: string, lang: Language): string {
  if (!text || lang === 'en') return text;
  const langDict = uiDictionary[lang];
  if (langDict && langDict[text]) {
    return langDict[text];
  }
  // Try case-insensitive trim
  const clean = text.trim();
  if (langDict && langDict[clean]) {
    return langDict[clean];
  }
  return text;
}
